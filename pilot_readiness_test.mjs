// The pilot check's rules (_shared/pilot-readiness.ts) on sample clients. node pilot_readiness_test.mjs
import path from 'path'; import { pathToFileURL } from 'url'
const pr = await import(pathToFileURL(path.resolve('supabase/functions/_shared/pilot-readiness.ts')).href)
const res = []; const ck = (n, c, note) => res.push([n, !!c, c ? '' : JSON.stringify(note ?? null).slice(0, 600)])
const base = { ax: '1', name: 'Dorothy Ray', state: 'MO', clientEmail: null, rpEmails: ['lisa@x.com'], circleEmails: ['lisa@x.com'], appOn: 0, rate: 30, rateFrom: 'client', about: true, recentCaregivers: 3, reachable: 3 }
let v = pr.verdict(base)
ck('1 everything there: ready, nothing missing', v.ready && !v.missing.length, v)
v = pr.verdict({ ...base, state: null })
ck('2 no state: not ready, says so', !v.ready && /no state/.test(v.missing[0]), v)
v = pr.verdict({ ...base, state: 'OK' })
ck('3 Oklahoma address: not ready (Missouri pilot)', !v.ready && /in OK, not Missouri/.test(v.missing[0]), v)
v = pr.verdict({ ...base, circleEmails: [] })
ck('4 email only on AxisCare: not ready yet, says it arrives overnight', !v.ready && /arrives overnight/.test(v.missing.join()), v)
v = pr.verdict({ ...base, circleEmails: [], rpEmails: [], clientEmail: 'dot@x.com' })
ck('5 the client\'s own AxisCare email is enough to sign in', v.ready, v)
v = pr.verdict({ ...base, circleEmails: [], rpEmails: [] })
ck('6 no email anywhere: not ready, says where to add one', !v.ready && /no family email/.test(v.missing.join()), v)
v = pr.verdict({ ...base, about: false })
ck('7 no About box: not ready', !v.ready && /About box/.test(v.missing.join()), v)
v = pr.verdict({ ...base, rate: null })
ck('8 no rate: not ready', !v.ready && /hourly rate/.test(v.missing.join()), v)
v = pr.verdict({ ...base, reachable: 1 })
ck('9 caregivers without a mobile: a note, still ready', v.ready && /2 of their 3 recent caregivers have no mobile/.test(v.notes.join()), v)
v = pr.verdict({ ...base, recentCaregivers: 0, reachable: 0 })
ck('10 no recent visits: a note (offers go to the team), still ready', v.ready && /wider team/.test(v.notes.join()), v)
v = pr.verdict({ ...base, rate: null, liveIn: true })
ck('8b live-in only: not ready, says booking is off (not "no rate")', !v.ready && /live-in only/.test(v.missing.join()) && !/hourly rate/.test(v.missing.join()), v)
const t = pr.report([{ ...base, name: 'Zed A', ax: '2' }, { ...base, name: 'Amy B', ax: '3', about: false, rate: null }, { ...base, name: 'Bo C', ax: '4', about: false }])
ck('11 report: ready first, then fewest gaps first; counts right', /READY FOR THE APP: 1 of 3/.test(t) && t.indexOf('Zed A') < t.indexOf('Bo C') && t.indexOf('Bo C') < t.indexOf('Amy B'), t)
ck('12 no em dashes in what she reads', !/—/.test(t))
for (const [n, ok, note] of res) console.log((ok ? '  ✓ ' : '  ✗ ') + n + (ok ? '' : '\n      ' + note))
console.log(`\n  pilot check rules: ${res.filter((r) => r[1]).length}/${res.length} passed`); process.exit(res.every((r) => r[1]) ? 0 : 1)
